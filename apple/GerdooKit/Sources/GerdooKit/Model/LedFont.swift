/// Hand-authored bitmap fonts for the LED panel, ported verbatim from
/// `src/shared/led-font.ts`.
///
/// Rows are strings of `1` (lit) and `0` (dark), top row first. Nothing here is
/// derived from a third-party typeface — the glyphs are plain dot-matrix cells,
/// which is why the panel can render on any device without shipping a font.
///
/// - `small`: 5x7 — labels, sub-labels.
/// - `big`: 8x14 digits plus a 3-wide colon — the countdown line.
import Foundation

public struct BitmapGlyph: Sendable {
  public let width: Int
  public let height: Int
  /// Row-major lit mask, `rows[y][x]`.
  public let mask: [[Bool]]

  init(_ rows: [String]) {
    width = rows[0].count
    height = rows.count
    mask = rows.map { row in row.map { $0 == "1" } }
  }
}

public struct BitmapFont: Sendable {
  public let height: Int
  /// Dots inserted between glyphs.
  public let tracking: Int
  let glyphs: [Character: BitmapGlyph]
  let fallback: BitmapGlyph

  init(_ source: [Character: [String]], tracking: Int) {
    var built: [Character: BitmapGlyph] = [:]
    var tallest = 0
    for (char, rows) in source {
      built[char] = BitmapGlyph(rows)
      tallest = max(tallest, rows.count)
    }
    height = tallest
    self.tracking = tracking
    glyphs = built
    fallback = built[" "]!
  }

  public func glyph(for char: Character) -> BitmapGlyph {
    glyphs[Character(char.uppercased())] ?? fallback
  }

  /// Width in dots of `text` rendered at `scale`.
  public func measure(_ text: String, scale: Int = 1) -> Int {
    if text.isEmpty { return 0 }
    var width = 0
    for char in text { width += glyph(for: char).width * scale + tracking * scale }
    return width - tracking * scale
  }
}

