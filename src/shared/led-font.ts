function buildFont(source: Record<string, string[]>, tracking: number): BitmapFont {
  const glyphs: Record<string, BitmapGlyph> = {}
  let height = 0
  for (const [char, rows] of Object.entries(source)) {
    glyphs[char] = glyph(rows)
    height = Math.max(height, rows.length)
  }
  return { height, tracking, glyphs, fallback: glyphs[' '] }
}

export const SMALL_FONT: BitmapFont = buildFont(SMALL_ROWS, 1)
export const BIG_FONT: BitmapFont = buildFont(BIG_ROWS, 2)

export function glyphFor(font: BitmapFont, char: string): BitmapGlyph {
  return font.glyphs[char.toUpperCase()] ?? font.fallback
}

/** Width in dots of `text` rendered with `font` at `scale`. */
export function measureText(font: BitmapFont, text: string, scale = 1): number {
  if (text.length === 0) return 0
  let width = 0
  for (const char of text) width += glyphFor(font, char).width * scale + font.tracking * scale
  return width - font.tracking * scale
}
