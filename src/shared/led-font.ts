/**
 * Hand-authored bitmap fonts for the LED panel.
 *
 * Rows are strings of `1` (lit) and `0` (dark), top row first. Nothing here is
 * derived from a third-party typeface — the glyphs are plain dot-matrix cells,
 * which is why the panel can render on any machine without shipping a font.
 *
 * SMALL: 5x7 — labels, sub-labels, scrolling text.
 * BIG:   8x14 digits + a 3-wide colon — the countdown line.
 */

export interface BitmapGlyph {
  width: number
  height: number
  rows: string[]
}

export interface BitmapFont {
  height: number
  /** Dots inserted between glyphs. */
  tracking: number
  glyphs: Record<string, BitmapGlyph>
  fallback: BitmapGlyph
}

function glyph(rows: string[]): BitmapGlyph {
  return { width: rows[0].length, height: rows.length, rows }
}

